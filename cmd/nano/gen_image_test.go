func TestGenerateImageWritesInlineImages(t *testing.T) {
	t.Setenv("IMAGE_URL_MAP", "")

	encoded := base64.StdEncoding.EncodeToString(testPNG)
	body := fmt.Sprintf(`{"data":[{"b64_json":%q},{"b64_json":%q}],"cost":0.02}`, encoded, encoded)

	server, requests := captureServer(t, http.StatusOK, body)
	dir := t.TempDir()

	out, _, err := runCommand(t, cli.Deps{Client: newClientAt(t, server.URL)},
		"generate", "image", "a cat",
		"--model", "image-model",
		"--n", "2",
		"--size", "1024x1024",
		"--seed", "42",
		"--strength", "0.5",
		"--guidance-scale", "7.5",
		"--num-inference-steps", "20",
		"--out", dir,
	)
	if err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	request := nextRequest(t, requests)
	if request.Path != "/api/v1/images/generations" {
		t.Errorf("path = %s, want /api/v1/images/generations", request.Path)
	}
	if auth := request.Header.Get("Authorization"); auth != "Bearer test-key" {
		t.Errorf("Authorization = %q, want Bearer test-key", auth)
	}

	bodyJSON := request.jsonBody(t)
	checks := map[string]any{
		"prompt":              "a cat",
		"model":               "image-model",
		"n":                   float64(2),
		"size":                "1024x1024",
		"response_format":     "b64_json",
		"seed":                float64(42),
		"strength":            0.5,
		"guidance_scale":      7.5,
		"num_inference_steps": float64(20),
	}
	for field, want := range checks {
		if bodyJSON[field] != want {
			t.Errorf("%s = %v, want %v", field, bodyJSON[field], want)
		}
	}

	files, err := filepath.Glob(filepath.Join(dir, "nano-image-*.png"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 2 {
		t.Fatalf("files = %v, want two images", files)
	}

	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("ReadFile(%s) error: %v", file, err)
		}
		if string(data) != string(testPNG) {
			t.Errorf("%s content = %q, want the generated bytes", file, data)
		}
	}

	if !strings.Contains(out, dir) || !strings.Contains(out, "Cost: $0.02") {
		t.Errorf("stdout does not contain the paths and cost:\n%s", out)
	}
}

func TestGenerateImageResolvesInputAddresses(t *testing.T) {
	t.Setenv("IMAGE_URL_MAP", "")

	input := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write(testPNG)
	}))
	defer input.Close()

	encoded := base64.StdEncoding.EncodeToString(testPNG)
	server, requests := captureServer(t, http.StatusOK,
		fmt.Sprintf(`{"data":[{"b64_json":%q}],"cost":0.01}`, encoded),
	)

	_, _, err := runCommand(t, cli.Deps{Client: newClientAt(t, server.URL)},
		"gen", "image", "a cat",
		"--image", input.URL+"/image.png",
		"--images", input.URL+"/extra.png",
		"--mask", input.URL+"/mask.png",
		"--out", t.TempDir(),
	)
	if err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	body := nextRequest(t, requests).jsonBody(t)
	wantDataURL := "data:image/png;base64," + encoded

	if body["imageDataUrl"] != wantDataURL {
		t.Errorf("imageDataUrl = %v, want the resolved input", body["imageDataUrl"])
	}
	if body["maskDataUrl"] != wantDataURL {
		t.Errorf("maskDataUrl = %v, want the resolved mask", body["maskDataUrl"])
	}

	images, ok := body["imageDataUrls"].([]any)
	if !ok || len(images) != 1 || images[0] != wantDataURL {
		t.Errorf("imageDataUrls = %v, want the resolved extra image", body["imageDataUrls"])
	}
}

func TestGenerateImageDownloadsAURLResult(t *testing.T) {
	t.Setenv("IMAGE_URL_MAP", "")

	var serverURL string
	server, requests := captureServerFunc(t, func(r *http.Request) (int, string) {
		switch r.URL.Path {
		case "/api/v1/images/generations":
			return http.StatusOK, fmt.Sprintf(`{"data":[{"url":%q}],"cost":0.03}`, serverURL+"/asset.png")
		case "/asset.png":
			return http.StatusOK, string(testPNG)
		default:
			return http.StatusNotFound, ""
		}
	})
	serverURL = server.URL

	dir := t.TempDir()

	if _, _, err := runCommand(t, cli.Deps{Client: newClientAt(t, server.URL)},
		"gen", "image", "a cat", "--out", dir,
	); err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	nextRequestPath(t, requests, "/api/v1/images/generations")

	files, err := filepath.Glob(filepath.Join(dir, "nano-image-*.png"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v, want one downloaded image", files)
	}

	data, err := os.ReadFile(files[0])
	if err != nil {
		t.Fatalf("ReadFile() error: %v", err)
	}
	if string(data) != string(testPNG) {
		t.Errorf("downloaded content = %q, want the asset bytes", data)
	}
}

func TestGenerateImageLeavesNoFileWhenADownloadFails(t *testing.T) {
	t.Setenv("IMAGE_URL_MAP", "")

	var serverURL string
	server, _ := captureServerFunc(t, func(r *http.Request) (int, string) {
		switch r.URL.Path {
		case "/api/v1/images/generations":
			return http.StatusOK, fmt.Sprintf(`{"data":[{"url":%q}],"cost":0.03}`, serverURL+"/asset.png")
		case "/asset.png":
			return http.StatusInternalServerError, "boom"
		default:
			return http.StatusNotFound, ""
		}
	})
	serverURL = server.URL

	dir := t.TempDir()

	_, _, err := runCommand(t, cli.Deps{Client: newClientAt(t, server.URL)},
		"gen", "image", "a cat", "--out", dir,
	)
	if err == nil || !strings.Contains(err.Error(), "gen image") {
		t.Fatalf("Execute() error = %v, want a download failure", err)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("ReadDir() error: %v", err)
	}
	if len(entries) != 0 {
		t.Errorf("output directory contains %d files, want none", len(entries))
	}
}

